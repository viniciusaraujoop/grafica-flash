import assert from 'node:assert/strict'
import {randomUUID} from 'node:crypto'
import AxeBuilder from '@axe-core/playwright'

export async function testWealthDebt({page,context,other,a,b,admin,appUrl,grant,active,ok,pass,errors,output}){
 await grant(a,{...active,permissions:['wealth.read','wealth.write','wealth.export']})
 const url=appUrl+'/apps/wealth/dividas'
 await page.goto(url)
 const form=page.getByRole('form',{name:'Nova dívida',exact:true})
 await form.getByLabel('Nome da dívida').fill('Dívida hospedada QA')
 await form.getByLabel('Saldo atual (R$)').fill('100,29')
 await form.getByLabel('Principal original (R$)').fill('100')
 await form.getByLabel('Juros fixos ao mês (%)').fill('1,50')
 await form.getByLabel('Pagamento mínimo mensal (R$)').fill('5')
 await form.getByLabel('Total de parcelas').fill('12');await form.getByLabel('Parcelas restantes').fill('10')
 await form.getByLabel('Próximo vencimento').fill('2026-10-05')
 await form.getByRole('checkbox').check()
 await form.evaluate((node,owner)=>{const input=document.createElement('input');input.name='user_id';input.type='hidden';input.value=owner;node.appendChild(input)},b.id)
 await form.getByRole('button',{name:'Salvar dívida',exact:true}).click()
 await form.getByRole('status').filter({hasText:'Dívida salva'}).waitFor()
 const entry=ok(await admin.from('wealth_entries').select('*').eq('title','Dívida hospedada QA').single())
 assert.equal(entry.user_id,a.id);assert.equal(entry.amount_cents,10029);assert.equal(entry.kind,'liability')
 const terms=ok(await a.db.from('wealth_debt_terms').select('*').eq('id',entry.id).single());assert.equal(terms.monthly_rate_bps,150);assert.equal(terms.principal_cents,10000)
 assert.deepEqual(ok(await b.db.from('wealth_debt_terms').select('*').eq('id',entry.id)),[])
 assert.equal(ok(await b.db.rpc('settle_wealth_debt',{p_entry_id:entry.id,p_version:entry.version,p_confirmed:true})),false)
 await other.page.goto(`${url}/${entry.id}`);await other.page.getByText('404',{exact:false}).first().waitFor()
 pass('debt-creation-Server-Action-exact-cents-linked-liability-and-cross-user-isolation')
 const sim=page.getByRole('form',{name:'Simular dívidas',exact:true})
 await sim.getByLabel('Orçamento mensal total (R$)').fill('30')
 for(const strategy of ['snowball','avalanche','custom']){
  await sim.getByLabel('Estratégia').selectOption(strategy);await sim.getByRole('button',{name:'Simular quitação'}).click()
  await page.getByText('Quitação simulada em 4 mês(es).',{exact:true}).waitFor()
 }
 await sim.getByLabel('Orçamento mensal total (R$)').fill('1');await sim.getByRole('button',{name:'Simular quitação'}).click()
 await page.getByText(/Orçamento insuficiente para os mínimos/).waitFor()
 const editUrl=`${url}/${entry.id}`
 await page.goto(editUrl)
 const edit=page.getByRole('form',{name:'Editar dívida',exact:true})
 const stale=await context.newPage();stale.on('pageerror',e=>errors.push(e.message));await stale.goto(editUrl)
 await edit.getByLabel('Saldo atual (R$)').fill('90,29');await edit.getByRole('checkbox').check();await edit.getByRole('button',{name:'Salvar dívida'}).click()
 await edit.getByRole('status').filter({hasText:'Dívida salva'}).waitFor()
 const old=stale.getByRole('form',{name:'Editar dívida',exact:true});assert.equal(await old.locator('input[name="version"]').inputValue(),'1');await old.getByRole('checkbox').check();assert.deepEqual(await old.locator('input').evaluateAll(inputs=>inputs.filter(i=>!i.validity.valid).map(i=>({name:i.name,value:i.value,message:i.validationMessage}))),[]);await old.getByRole('button',{name:'Salvar dívida'}).click()
 await old.getByRole('status').waitFor();assert.match(await old.getByRole('status').innerText(),/mudou em outra aba/);await stale.close()
 assert.equal(ok(await admin.from('wealth_entries').select('amount_cents').eq('id',entry.id).single()).amount_cents,9029)
 await grant(a,{...active,permissions:['wealth.read']})
 await edit.getByRole('checkbox').check();await edit.getByRole('button',{name:'Salvar dívida'}).click()
 await edit.getByRole('status').filter({hasText:'não permite alterar dívidas'}).waitFor()
 await grant(a,{...active,permissions:['wealth.read','wealth.write','wealth.export']});await page.reload()
 const payoff=page.getByRole('form',{name:'Declarar quitação',exact:true});await payoff.getByRole('checkbox').check();await payoff.getByRole('button',{name:'Declarar quitação'}).click()
 await page.waitForFunction(()=>!document.querySelector('form[aria-label="Declarar quitação"]'))
 const settled=ok(await admin.from('wealth_entries').select('amount_cents').eq('id',entry.id).single());assert.equal(settled.amount_cents,0)
 assert.equal(ok(await a.db.from('wealth_debt_terms').select('remaining_installments').eq('id',entry.id).single()).remaining_installments,0)
 pass('debt-simulator-three-strategies-insufficient-budget-edit-stale-read-only-and-declared-payoff')
 // Extend an existing liability in place; the debt form must not create a second balance.
 const existing=ok(await a.db.from('wealth_entries').insert({user_id:a.id,kind:'liability',title:'Passivo existente QA',category:'loan',amount_cents:157,financial_date:'2026-09-26',recurrence:'none',idempotency_key:randomUUID()}).select('id').single())
 await page.goto(`${url}/${existing.id}`)
 const extend=page.getByRole('form',{name:'Editar dívida',exact:true});await extend.getByRole('checkbox').check();await extend.getByRole('button',{name:'Salvar dívida'}).click()
 await extend.getByRole('status').filter({hasText:'Dívida salva'}).waitFor()
 assert.equal(ok(await admin.from('wealth_entries').select('id').eq('title','Passivo existente QA')).length,1)
 assert.equal(ok(await a.db.from('wealth_debt_terms').select('id').eq('id',existing.id).single()).id,existing.id)
 const axeEdit=await new AxeBuilder({page}).withTags(['wcag2a','wcag2aa','wcag21aa']).analyze();assert.deepEqual(axeEdit.violations.map(v=>v.id),[])
 await page.goto(url)
 const axe=await new AxeBuilder({page}).withTags(['wcag2a','wcag2aa','wcag21aa']).analyze();assert.deepEqual(axe.violations.map(v=>v.id),[])
 for(const width of [320,390,768,1440]){await page.setViewportSize({width,height:900});assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),`Debt overflow ${width}`)}
 await page.setViewportSize({width:390,height:1000});await page.screenshot({path:`${output}/debt-hosted.png`,fullPage:true})
 const audit=ok(await admin.from('ecosystem_audit_events').select('event_type,entity_id').in('entity_id',[entry.id,existing.id]))
 assert.ok(audit.some(e=>e.event_type==='wealth_debt_terms.insert'));assert.ok(audit.some(e=>e.event_type==='wealth_debt_terms.update'))
 pass('debt-existing-liability-reuse-private-audit-and-responsive-WCAG')
}
